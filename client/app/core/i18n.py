STRINGS = {"zh_CN": ZH, "en_US": EN, "zh_TW": TW}


class I18n(QObject):
    languageChanged = Signal()
    languageVersion = Property(int, lambda self: self._version, notify=languageChanged)

    def __init__(self, settings, parent=None):  # noqa: ANN001
        super().__init__(parent)
        self._settings = settings
        self._lang = settings.language if settings.language in LANGS else "zh_CN"
        self._version = 0

    @Slot(result=str)
    def language(self) -> str:
        return self._lang

    @Slot(str)
    def setLanguage(self, code: str) -> None:
        if code not in LANGS:
            code = "zh_CN"
        if code == self._lang:
            return
        self._lang = code
        self._settings.language = code
        self._version += 1
        self.languageChanged.emit()

    @Slot(result="QVariantMap")
    def bundle(self) -> QVariantMap:
        data = dict(ZH)
        data.update(STRINGS.get(self._lang, ZH))
        data["lang"] = self._lang
        return data

    @Slot(str, result=str)
    def t(self, key: str) -> str:
        return STRINGS.get(self._lang, ZH).get(key, ZH.get(key, key))
